import asyncio
import base64
import json
import logging
import os
import signal
from typing import Any

from aiokafka import AIOKafkaConsumer, AIOKafkaProducer
from aiokafka.errors import KafkaError
from aiokafka.structs import ConsumerRecord, TopicPartition
from dotenv import load_dotenv
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool
from pydantic import ValidationError

from app.models import PingCreate
from app.ping_parser import parse_ping

load_dotenv()

logger = logging.getLogger(__name__)

CREATE_PINGS_TABLE = """
CREATE TABLE IF NOT EXISTS pings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id TEXT NOT NULL,
    sequence_number BIGINT,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    speed_kmh DOUBLE PRECISION NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""

ALTER_PINGS_TABLE_SEQUENCE = """
ALTER TABLE pings
ADD COLUMN IF NOT EXISTS sequence_number BIGINT
"""

CREATE_VEHICLE_INDEX = """
CREATE INDEX IF NOT EXISTS idx_pings_vehicle_recorded
ON pings (vehicle_id, recorded_at DESC)
"""

CREATE_UNIQUE_PING_INDEX = """
CREATE UNIQUE INDEX IF NOT EXISTS idx_pings_vehicle_sequence
ON pings (vehicle_id, sequence_number)
WHERE sequence_number IS NOT NULL
"""


def initialize_database(pool: ConnectionPool) -> None:
    with pool.connection() as connection:
        connection.execute(CREATE_PINGS_TABLE)
        connection.execute(ALTER_PINGS_TABLE_SEQUENCE)
        connection.execute(CREATE_VEHICLE_INDEX)
        connection.execute(CREATE_UNIQUE_PING_INDEX)


def save_ping(pool: ConnectionPool, ping: PingCreate) -> bool:
    if ping.sequence_number is None:
        raise ValueError("A Kafka ping must include sequence_number")
    with pool.connection() as connection:
        row = connection.execute(
            """
            INSERT INTO pings (
                vehicle_id, sequence_number, latitude, longitude,
                speed_kmh, recorded_at
            )
            VALUES (%s, %s, %s, %s, %s, %s)
            ON CONFLICT (vehicle_id, sequence_number)
            WHERE sequence_number IS NOT NULL
            DO NOTHING
            RETURNING id
            """,
            (
                ping.vehicle_id,
                ping.sequence_number,
                ping.latitude,
                ping.longitude,
                ping.speed_kmh,
                ping.recorded_at,
            ),
        ).fetchone()
    return row is not None


def dlq_payload(record: ConsumerRecord[bytes, bytes], reason: str) -> bytes:
    value = record.value
    return json.dumps(
        {
            "reason": reason,
            "original": (value or b"").decode("utf-8", errors="replace"),
            "original_base64": (
                base64.b64encode(value).decode("ascii") if value is not None else None
            ),
            "source": {
                "topic": record.topic,
                "partition": record.partition,
                "offset": record.offset,
            },
        },
        separators=(",", ":"),
    ).encode("utf-8")


async def retry_database_insert(
    pool: ConnectionPool,
    ping: PingCreate,
    record: Any,
    stopping: asyncio.Event,
) -> bool:
    while not stopping.is_set():
        try:
            duplicate = not await asyncio.to_thread(save_ping, pool, ping)
            if duplicate:
                logger.info(
                    "Ignored duplicate vehicle=%s sequence=%s",
                    ping.vehicle_id,
                    ping.sequence_number,
                )
            return True
        except Exception:
            logger.exception(
                "Database insert failed; retrying exact "
                "topic=%s partition=%s offset=%s",
                record.topic,
                record.partition,
                record.offset,
            )
            await asyncio.sleep(1)
    return False


async def retry_dlq_publish(
    producer: AIOKafkaProducer,
    record: Any,
    payload: bytes,
    stopping: asyncio.Event,
) -> bool:
    while not stopping.is_set():
        try:
            await producer.send_and_wait(
                "pings-dlq",
                key=record.key,
                value=payload,
            )
            return True
        except (KafkaError, asyncio.TimeoutError):
            logger.exception(
                "Could not publish malformed record to pings-dlq; "
                "retrying exact topic=%s partition=%s offset=%s",
                record.topic,
                record.partition,
                record.offset,
            )
            await asyncio.sleep(1)
    return False


async def run_writer() -> None:
    database_url = os.getenv("DATABASE_URL")
    if not database_url:
        raise RuntimeError("DATABASE_URL is required for the Kafka writer.")

    bootstrap_servers = os.getenv(
        "KAFKA_BOOTSTRAP_SERVERS",
        "geopulse-kafka-bootstrap.kafka.svc:9092",
    )
    consumer = AIOKafkaConsumer(
        "pings",
        bootstrap_servers=bootstrap_servers,
        group_id=os.getenv("KAFKA_GROUP_ID", "geopulse-ping-writer"),
        enable_auto_commit=False,
        auto_offset_reset="earliest",
    )
    producer = AIOKafkaProducer(
        bootstrap_servers=bootstrap_servers,
        acks="all",
        enable_idempotence=True,
    )
    pool = ConnectionPool(
        conninfo=database_url,
        min_size=1,
        max_size=4,
        kwargs={"row_factory": dict_row},
        open=False,
    )
    pool.open(wait=True)
    stopping = asyncio.Event()

    for sig in (signal.SIGINT, signal.SIGTERM):
        try:
            asyncio.get_running_loop().add_signal_handler(sig, stopping.set)
        except NotImplementedError:
            pass

    try:
        await asyncio.to_thread(initialize_database, pool)
        await producer.start()
        await consumer.start()
        logger.info("Kafka ping writer started")

        async for record in consumer:
            if stopping.is_set():
                break
            try:
                ping = await asyncio.to_thread(parse_ping, record.value)
            except (json.JSONDecodeError, UnicodeDecodeError, ValidationError, ValueError) as error:
                payload = dlq_payload(record, str(error))
                published = await retry_dlq_publish(
                    producer,
                    record,
                    payload,
                    stopping,
                )
                if published:
                    logger.warning("Sent invalid ping to pings-dlq: %s", error)
                if stopping.is_set():
                    break
            else:
                stored = await retry_database_insert(
                    pool,
                    ping,
                    record,
                    stopping,
                )
                if not stored:
                    break
                if stopping.is_set():
                    break

            await consumer.commit(
                {
                    TopicPartition(record.topic, record.partition):
                        record.offset + 1
                }
            )
    finally:
        await consumer.stop()
        await producer.stop()
        pool.close()


if __name__ == "__main__":
    try:
        asyncio.run(run_writer())
    except KeyboardInterrupt:
        pass
