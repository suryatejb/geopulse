import asyncio
import json
import logging
import os
import time
from contextlib import asynccontextmanager
from datetime import datetime, timezone
from typing import AsyncIterator

from aiokafka import AIOKafkaProducer
from aiokafka.errors import KafkaError
from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException, Query, Request, Response, status
from fastapi.responses import FileResponse
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool
from redis import Redis
from redis.exceptions import RedisError
from starlette.concurrency import run_in_threadpool

from app.area_stats import read_area_stats
from app.geo import location_cell
from app.models import AreaStats, PingAccepted, PingCount, PingCreate, PingResponse

load_dotenv()

logger = logging.getLogger(__name__)
KAFKA_PUBLISH_TIMEOUT_SECONDS = 5.0

CREATE_PINGS_TABLE = """
CREATE TABLE IF NOT EXISTS pings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id TEXT NOT NULL,
    sequence_number BIGINT,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    speed_kmh DOUBLE PRECISION NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""

CREATE_VEHICLE_TIME_INDEX = """
CREATE INDEX IF NOT EXISTS idx_pings_vehicle_recorded
ON pings (vehicle_id, recorded_at DESC)
"""

CREATE_UNIQUE_PING_INDEX = """
CREATE UNIQUE INDEX IF NOT EXISTS idx_pings_vehicle_sequence
ON pings (vehicle_id, sequence_number)
WHERE sequence_number IS NOT NULL
"""

ALTER_PINGS_TABLE_SEQUENCE = """
ALTER TABLE pings
ADD COLUMN IF NOT EXISTS sequence_number BIGINT
"""


def create_app() -> FastAPI:
    ingestion_mode = os.getenv("PING_INGESTION_MODE", "postgres").strip().lower()
    if ingestion_mode not in {"postgres", "kafka"}:
        raise RuntimeError("PING_INGESTION_MODE must be 'postgres' or 'kafka'.")

    @asynccontextmanager
    async def lifespan(app: FastAPI) -> AsyncIterator[None]:
        database_url = os.getenv("DATABASE_URL")
        if not database_url:
            raise RuntimeError(
                "DATABASE_URL is missing. Copy .env.example to .env and set your "
                "local PostgreSQL password."
            )

        pool = ConnectionPool(
            conninfo=database_url,
            min_size=1,
            max_size=10,
            kwargs={"row_factory": dict_row},
            open=False,
        )
        pool.open(wait=True)
        producer = None
        redis_client = None
        try:
            with pool.connection() as connection:
                connection.execute(CREATE_PINGS_TABLE)
                connection.execute(ALTER_PINGS_TABLE_SEQUENCE)
                connection.execute(CREATE_VEHICLE_TIME_INDEX)
                connection.execute(CREATE_UNIQUE_PING_INDEX)
            app.state.pool = pool
            redis_url = os.getenv("REDIS_URL")
            if redis_url:
                redis_client = Redis.from_url(redis_url)
                app.state.redis = redis_client
            if ingestion_mode == "kafka":
                producer = AIOKafkaProducer(
                    bootstrap_servers=os.getenv(
                        "KAFKA_BOOTSTRAP_SERVERS",
                        "geopulse-kafka-bootstrap.kafka.svc:9092",
                    ),
                    acks="all",
                    enable_idempotence=True,
                )
                await producer.start()
                app.state.kafka_producer = producer
            yield
        finally:
            if producer is not None:
                await producer.stop()
            if redis_client is not None:
                redis_client.close()
            pool.close()

    app = FastAPI(
        title="GeoPulse",
        description="Collects simulated vehicle GPS pings in PostgreSQL or Kafka.",
        version="0.1.0",
        lifespan=lifespan,
    )
    app.state.ingestion_mode = ingestion_mode

    @app.middleware("http")
    async def add_api_timing(request: Request, call_next):
        started_at = time.perf_counter()
        response = await call_next(request)
        api_ms = (time.perf_counter() - started_at) * 1000
        server_timing = response.headers.get("Server-Timing")
        api_timing = f"api;dur={api_ms:.3f}"
        response.headers["Server-Timing"] = (
            f"{server_timing}, {api_timing}" if server_timing else api_timing
        )
        return response

    @app.get("/livez")
    async def livez() -> dict[str, str]:
        return {"status": "ok"}

    @app.get("/health")
    def health(request: Request) -> dict[str, str]:
        with request.app.state.pool.connection() as connection:
            connection.execute("SELECT 1")
        return {"status": "ok", "database": "ok"}

    @app.get("/dashboard", include_in_schema=False)
    def dashboard() -> FileResponse:
        return FileResponse(os.path.join(os.path.dirname(__file__), "dashboard.html"))

    @app.get("/api/v1/stats/area", response_model=AreaStats)
    def area_stats(
        request: Request,
        latitude: float = Query(ge=-90, le=90),
        longitude: float = Query(ge=-180, le=180),
        minute_start: int | None = Query(default=None, ge=0, multiple_of=60),
    ) -> AreaStats:
        client = getattr(request.app.state, "redis", None)
        if client is None:
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Live statistics are not configured.",
            )

        if minute_start is None:
            minute_start = (int(time.time()) // 60 * 60) - 60
        cell = location_cell(latitude, longitude)
        try:
            stats = read_area_stats(
                client, cell=cell, minute_start=minute_start
            )
        except RedisError:
            logger.exception("Could not read live statistics from Redis")
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Live statistics are temporarily unavailable.",
            ) from None
        if stats is None:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="No statistics are available for this area and minute.",
            )
        vehicle_count, average_speed_kmh = stats
        return AreaStats(
            h3_cell=cell,
            minute_start=minute_start,
            vehicle_count=vehicle_count,
            average_speed_kmh=average_speed_kmh,
        )

    @app.post(
        "/api/v1/pings",
        response_model=PingResponse | PingAccepted,
        status_code=status.HTTP_201_CREATED,
        responses={
            status.HTTP_200_OK: {"model": PingResponse},
            status.HTTP_202_ACCEPTED: {"model": PingAccepted},
        },
    )
    async def create_ping(
        ping: PingCreate, request: Request, response: Response
    ) -> dict | PingAccepted:
        if ingestion_mode == "kafka":
            if ping.sequence_number is None:
                raise HTTPException(
                    status_code=422,
                    detail="sequence_number is required for Kafka ingestion.",
                )
            kafka_ping = ping.model_dump(mode="json")
            kafka_ping["h3_cell"] = location_cell(ping.latitude, ping.longitude)
            kafka_send_started_at = time.perf_counter()
            try:
                await asyncio.wait_for(
                    request.app.state.kafka_producer.send_and_wait(
                        "pings",
                        key=ping.vehicle_id.encode("utf-8"),
                        value=json.dumps(
                            kafka_ping,
                            separators=(",", ":"),
                        ).encode("utf-8"),
                    ),
                    timeout=KAFKA_PUBLISH_TIMEOUT_SECONDS,
                )
            except (KafkaError, asyncio.TimeoutError):
                logger.exception(
                    "Kafka did not acknowledge ping for vehicle %s sequence %d",
                    ping.vehicle_id,
                    ping.sequence_number,
                )
                raise HTTPException(
                    status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                    detail="Kafka did not acknowledge the ping; it may still be published.",
                ) from None
            response.status_code = status.HTTP_202_ACCEPTED
            response.headers["Server-Timing"] = (
                f"kafka_send;dur="
                f"{(time.perf_counter() - kafka_send_started_at) * 1000:.3f}"
            )
            return PingAccepted(
                vehicle_id=ping.vehicle_id,
                sequence_number=ping.sequence_number,
                recorded_at=ping.recorded_at,
                accepted_at=datetime.now(timezone.utc),
            )

        def save_ping() -> dict:
            pool_wait_started_at = time.perf_counter()
            with request.app.state.pool.connection() as connection:
                connection_acquired_at = time.perf_counter()
                db_pool_ms = (connection_acquired_at - pool_wait_started_at) * 1000
                db_execute_started_at = time.perf_counter()
                row = connection.execute(
                    """
                    INSERT INTO pings (
                        vehicle_id, sequence_number, latitude, longitude,
                        speed_kmh, recorded_at
                    )
                    VALUES (%s, %s, %s, %s, %s, %s)
                    ON CONFLICT (vehicle_id, sequence_number)
                    WHERE sequence_number IS NOT NULL DO NOTHING
                    RETURNING id, vehicle_id, sequence_number, latitude, longitude,
                              speed_kmh,
                              recorded_at, received_at
                    """,
                    (
                        ping.vehicle_id,
                        ping.sequence_number,
                        ping.latitude,
                        ping.longitude,
                        ping.speed_kmh,
                        ping.recorded_at,
                    ),
                ).fetchone()
                if row is None and ping.sequence_number is not None:
                    row = connection.execute(
                        """
                        SELECT id, vehicle_id, sequence_number, latitude, longitude,
                               speed_kmh, recorded_at, received_at
                        FROM pings WHERE vehicle_id = %s AND sequence_number = %s
                        """,
                        (ping.vehicle_id, ping.sequence_number),
                    ).fetchone()
                    if row is not None:
                        response.status_code = status.HTTP_200_OK
                db_execute_ms = (time.perf_counter() - db_execute_started_at) * 1000
            db_transaction_ms = (time.perf_counter() - connection_acquired_at) * 1000
            if row is None:
                raise HTTPException(
                    status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                    detail="The database did not return the saved ping.",
                )
            response.headers["Server-Timing"] = (
                f"db_pool;dur={db_pool_ms:.3f}, "
                f"db_execute;dur={db_execute_ms:.3f}, "
                f"db_transaction;dur={db_transaction_ms:.3f}"
            )
            return row

        return await run_in_threadpool(save_ping)

    @app.get("/api/v1/pings/count", response_model=PingCount)
    def count_pings(request: Request) -> dict[str, int]:
        with request.app.state.pool.connection() as connection:
            row = connection.execute("SELECT COUNT(*) AS count FROM pings").fetchone()
        if row is None:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="The database did not return the ping count.",
            )
        return row

    return app


app = create_app()
