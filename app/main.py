import os
import time
from contextlib import asynccontextmanager
from typing import AsyncIterator

from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException, Request, Response, status
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

from app.models import PingCount, PingCreate, PingResponse

load_dotenv()

CREATE_PINGS_TABLE = """
CREATE TABLE IF NOT EXISTS pings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    speed_kmh DOUBLE PRECISION NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)
"""

CREATE_VEHICLE_TIME_INDEX = """
CREATE INDEX IF NOT EXISTS idx_pings_vehicle_recorded
ON pings (vehicle_id, recorded_at DESC)
"""


def create_app() -> FastAPI:
    @asynccontextmanager
    async def lifespan(app: FastAPI) -> AsyncIterator[None]:
        database_url = os.getenv("DATABASE_URL")
        if not database_url:
            raise RuntimeError(
                "DATABASE_URL is missing. Copy .env.example to .env and set your "
                "local PostgreSQL password."
            )

        pool = ConnectionPool(
            conninfo=database_url,
            min_size=1,
            max_size=10,
            kwargs={"row_factory": dict_row},
            open=False,
        )
        pool.open(wait=True)
        try:
            with pool.connection() as connection:
                connection.execute(CREATE_PINGS_TABLE)
                connection.execute(CREATE_VEHICLE_TIME_INDEX)
            app.state.pool = pool
            yield
        finally:
            pool.close()

    app = FastAPI(
        title="GeoPulse",
        description="A baseline API for collecting simulated vehicle GPS pings.",
        version="0.1.0",
        lifespan=lifespan,
    )

    @app.middleware("http")
    async def add_api_timing(request: Request, call_next):
        started_at = time.perf_counter()
        response = await call_next(request)
        api_ms = (time.perf_counter() - started_at) * 1000
        server_timing = response.headers.get("Server-Timing")
        api_timing = f"api;dur={api_ms:.3f}"
        response.headers["Server-Timing"] = (
            f"{server_timing}, {api_timing}" if server_timing else api_timing
        )
        return response

    @app.get("/health")
    def health(request: Request) -> dict[str, str]:
        with request.app.state.pool.connection() as connection:
            connection.execute("SELECT 1")
        return {"status": "ok", "database": "ok"}

    @app.post(
        "/api/v1/pings",
        response_model=PingResponse,
        status_code=status.HTTP_201_CREATED,
    )
    def create_ping(ping: PingCreate, request: Request, response: Response) -> dict:
        pool_wait_started_at = time.perf_counter()
        with request.app.state.pool.connection() as connection:
            connection_acquired_at = time.perf_counter()
            db_pool_ms = (connection_acquired_at - pool_wait_started_at) * 1000
            db_execute_started_at = time.perf_counter()
            row = connection.execute(
                """
                INSERT INTO pings (
                    vehicle_id, latitude, longitude, speed_kmh, recorded_at
                )
                VALUES (%s, %s, %s, %s, %s)
                RETURNING id, vehicle_id, latitude, longitude, speed_kmh,
                          recorded_at, received_at
                """,
                (
                    ping.vehicle_id,
                    ping.latitude,
                    ping.longitude,
                    ping.speed_kmh,
                    ping.recorded_at,
                ),
            ).fetchone()
            db_execute_ms = (time.perf_counter() - db_execute_started_at) * 1000
        db_transaction_ms = (time.perf_counter() - connection_acquired_at) * 1000
        if row is None:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="The database did not return the saved ping.",
            )
        response.headers["Server-Timing"] = (
            f"db_pool;dur={db_pool_ms:.3f}, "
            f"db_execute;dur={db_execute_ms:.3f}, "
            f"db_transaction;dur={db_transaction_ms:.3f}"
        )
        return row

    @app.get("/api/v1/pings/count", response_model=PingCount)
    def count_pings(request: Request) -> dict[str, int]:
        with request.app.state.pool.connection() as connection:
            row = connection.execute("SELECT COUNT(*) AS count FROM pings").fetchone()
        if row is None:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="The database did not return the ping count.",
            )
        return row

    return app


app = create_app()
